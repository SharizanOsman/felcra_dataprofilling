using Felcra.Profiling.Application.Abstractions;

namespace Felcra.Profiling.Infrastructure.Storage;

public sealed class FileStoreOptions
{
    public const string SectionName = "Storage";

    /// <summary>Folder for uploaded files. Relative paths are resolved against the app's content root.</summary>
    public string Path { get; set; } = "App_Data/uploads";
}

/// <summary>Stores files on local disk as {yyyy}/{MM}/{guid}{ext}. In Docker, mount this folder as a volume.</summary>
internal sealed class LocalFileStore(string root, TimeProvider clock) : IFileStore
{
    public async Task<string> SaveAsync(Stream content, string extension, CancellationToken ct = default)
    {
        var now = clock.GetUtcNow();
        var key = $"{now:yyyy}/{now:MM}/{Guid.CreateVersion7():N}{extension}";
        var path = FullPath(key);
        Directory.CreateDirectory(System.IO.Path.GetDirectoryName(path)!);

        await using var file = new FileStream(path, FileMode.CreateNew, FileAccess.Write);
        await content.CopyToAsync(file, ct);
        return key;
    }

    public Stream? OpenRead(string storageKey)
    {
        var path = FullPath(storageKey);
        return File.Exists(path) ? File.OpenRead(path) : null;
    }

    private string FullPath(string key)
    {
        // Keys are generated by SaveAsync; still refuse anything that would escape the root folder.
        var full = System.IO.Path.GetFullPath(System.IO.Path.Combine(root, key));
        if (!full.StartsWith(System.IO.Path.GetFullPath(root), StringComparison.OrdinalIgnoreCase))
            throw new InvalidOperationException("Invalid storage key.");
        return full;
    }
}
